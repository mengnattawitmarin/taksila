export function dreamLookup(text) {
  const t = text.replace(/\s+/g, '');
  let best = null;
  for (const d of DREAMS) for (const k of d.k) if (t.includes(k) && (!best || k.length > best.len)) best = { ...d, len: k.length, key: k };
  return best;
}
