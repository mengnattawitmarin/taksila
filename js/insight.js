// ---------- dignity (classical; Thai terms เกษตร อุจ ประ นิจ) ----------
const DOMICILE_SIGNS = { sun: [4], moon: [3], mercury: [2, 5], venus: [1, 6], mars: [0, 7], jupiter: [8, 11], saturn: [9, 10] };
const EXALT_SIGN = { sun: 0, moon: 1, mercury: 5, venus: 11, mars: 9, jupiter: 3, saturn: 6 };
const opp = (s) => (s + 6) % 12;
export function dignityOf(id, sign) {
  if (!DOMICILE_SIGNS[id]) return null;
  if (DOMICILE_SIGNS[id].includes(sign)) return { id: 'dom', th: 'เกษตร', en: 'domicile', score: 2, d: 'อยู่บ้านตัวเอง แสดงพลังได้เต็มที่' };
  if (EXALT_SIGN[id] === sign) return { id: 'ex', th: 'อุจ', en: 'exaltation', score: 2, d: 'อยู่ราศีที่ส่งเสริมสูงสุด ได้รับการยกย่อง' };
  if (DOMICILE_SIGNS[id].map(opp).includes(sign)) return { id: 'det', th: 'ประ', en: 'detriment', score: -1, d: 'อยู่ราศีตรงข้ามบ้าน ต้องออกแรงมากกว่าปกติ' };
  if (opp(EXALT_SIGN[id]) === sign) return { id: 'fall', th: 'นิจ', en: 'fall', score: -2, d: 'อยู่ราศีที่พลังอ่อนที่สุด เป็นบทเรียนของชีวิต' };
  return null;
}
// Traditional sign rulers (Aries..Pisces).
export const SIGN_RULER = ['mars', 'venus', 'mercury', 'moon', 'sun', 'mercury', 'venus', 'mars', 'jupiter', 'saturn', 'saturn', 'jupiter'];

// The lord of a house: which planet rules it, where that planet sits and how strong it is.
export function houseLord(chart, house) {
  const sign = (chart.firstSign + house - 1) % 12;
  const pl = chart.planets.find((p) => p.id === SIGN_RULER[sign]);
  const dg = dignityOf(pl.id, pl.sign);
  const same = pl.house === house;
  const text = `เจ้าเรือนภพ ${house} (${HOUSES[house - 1]}) คือดาว${pl.th} ${same ? `อยู่ในภพของตัวเอง เรื่องนี้จึงมั่นคงและเป็นตัวของตัวเอง` : `ไปอยู่ภพ ${pl.house} เรื่อง${HOUSES[house - 1].split(' ')[0]}ของคุณจึงผูกกับเรื่อง${HOUSES[pl.house - 1]}`}${dg ? ` · ดาว${pl.th}${dg.th} (${dg.d})` : ''}`;
  const tone = (dg ? dg.score : 0) + ([1, 4, 5, 7, 9, 10, 11].includes(pl.house) ? 1 : [6, 8, 12].includes(pl.house) ? -1 : 0) + (pl.retro ? -0.5 : 0);
  return { house, sign, planet: pl, dignity: dg, text, tone };
}

