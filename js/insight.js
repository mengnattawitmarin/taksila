const NUM_MEAN = { 1: 'การเริ่มต้นใหม่', 2: 'ทางเลือกและการจับคู่', 3: 'การเติบโตและความร่วมมือ', 4: 'ความมั่นคงที่อาจหยุดนิ่ง', 5: 'ความเปลี่ยนแปลงและแรงเสียดทาน', 6: 'ความกลมเกลียวและการให้', 7: 'บททดสอบและการทบทวน', 8: 'การเคลื่อนไหวและพลังอำนาจ', 9: 'ใกล้ถึงปลายทาง', 10: 'การปิดวงจร' };
export function tarotSynthesis(cards) {
  const n = cards.length, out = [];
  if (n < 2) return out;
  const majors = cards.filter((x) => x.c.major).length;
  const rev = cards.filter((x) => x.rev).length;
  const courts = cards.filter((x) => !x.c.major && x.c.n >= 11).length;
  const suits = { w: 0, c: 0, s: 0, p: 0 };
  cards.forEach((x) => { if (x.c.suit) suits[x.c.suit] += 1; });
  const ranked = Object.entries(suits).sort((a, b) => b[1] - a[1]);
  if (majors / n >= 0.5) out.push(`ไพ่ชุดใหญ่ ${majors} จาก ${n} ใบ เรื่องนี้เป็นจังหวะชีวิตที่ใหญ่กว่าเรื่องประจำวัน ชะตากำลังพาเปลี่ยน`);
  else if (majors === 0) out.push('ไม่มีไพ่ชุดใหญ่เลย เรื่องนี้อยู่ในมือคุณ แก้ได้ด้วยการตัดสินใจของตัวเอง');
  if (ranked[0][1] >= Math.max(2, Math.ceil(n / 2))) out.push(`ไพ่${SUIT_TH[ranked[0][0]].th}เด่น ${ranked[0][1]} ใบ แก่นของเรื่องคือ${SUIT_TH[ranked[0][0]].more}`);
  if (n >= 5) { const miss = ranked.filter((r) => r[1] === 0).map((r) => r[0]); if (miss.length === 1) out.push(`ไม่มีไพ่${SUIT_TH[miss[0]].th}เลย ${SUIT_TH[miss[0]].none}`); }
  if (courts >= 2) out.push(`ไพ่ราชสำนัก ${courts} ใบ มีคนหลายคนเกี่ยวข้องกับเรื่องนี้ ความสัมพันธ์กับคนรอบตัวคือกุญแจ`);
  if (rev / n >= 0.5) out.push(`ไพ่กลับหัว ${rev} ใบ พลังยังติดขัดหรือหันเข้าข้างใน ต้องแก้ที่ใจหรือสิ่งค้างคาก่อน`);
  const nums = {};
  cards.forEach((x) => { if (!x.c.major && x.c.n <= 10) nums[x.c.n] = (nums[x.c.n] || 0) + 1; });
  const rep = Object.entries(nums).filter(([, k]) => k >= 2).sort((a, b) => b[1] - a[1])[0];
  if (rep) out.push(`เลข ${rep[0]} ซ้ำ ${rep[1]} ใบ ย้ำพลังของ${NUM_MEAN[rep[0]]}`);
  return out;
}

