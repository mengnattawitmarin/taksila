// Daily: the hardest transit from a troubling planet decides the chant; otherwise the birth-day chant strengthens the day.
export function dailyRemedy(aspects, birthPlanetNo, totalScore) {
  const hard = aspects.find((x) => x.asp.nature < 0 && ['saturn', 'mars', 'uranus', 'neptune', 'pluto'].includes(x.mover.id) && x.strength > 0.5);
  if (hard) return { id: PLANET_DAY[hard.mover.id], kind: 'แก้', reason: `ดาว${hard.mover.th}จรทำมุม${hard.asp.th}กับดวงของคุณ ตำราให้บูชาเทวดาประจำดาวนั้น` };
  if (totalScore < 50) return { id: 'chinabanchon', kind: 'แก้', reason: 'ดวงวันนี้ค่อนข้างตึง สวดชินบัญชรเพื่อคุ้มครองและตั้งสติ' };
  return { id: THAI_DAY[birthPlanetNo], kind: 'เสริม', reason: 'บทสวดประจำวันเกิดของคุณ เสริมสิริมงคลให้วันนี้' };
}
// Tarot: troubling cards get a chant that matches the suit's area of life.
export function tarotRemedy(card, reversed) {
  const lean = reversed ? (card.yes === 1 ? 0 : -1) : card.yes;
  if (lean >= 0) return null;
  if (card.major) return { id: 'chinabanchon', kind: 'แก้', reason: 'ไพ่ชุดใหญ่ที่เตือนเรื่องหนัก สวดชินบัญชรเพื่อคุ้มครองและตั้งสติ' };
  const bySuit = { c: ['metta-all', 'เรื่องหัวใจ แผ่เมตตาช่วยคลายเวรและเปิดใจกัน'], s: ['heart-sati', 'ความคิดวุ่นวาย ภาวนาหัวใจสติปัฏฐานให้ใจนิ่ง'], w: ['bahung', 'มีอุปสรรคในการลงมือ บทพาหุงฯ เพื่อชัยชนะ'], p: ['heart-setthi', 'เรื่องเงินตึง ภาวนาหัวใจเศรษฐีพร้อมทำตามหลักทั้ง 4'] };
  const [id, reason] = bySuit[card.suit];
  return { id, kind: 'แก้', reason };
}
